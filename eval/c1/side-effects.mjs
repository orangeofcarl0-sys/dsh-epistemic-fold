/**
 * EF-C1 WP0 — the side-effect inventory.
 *
 * ## What this answers
 *
 * "Which code can write into the repository, what triggers it, and is that
 * write legitimate?" A static scan alone cannot answer it: `writeFile(join(root,
 * 'report.json'))` and `writeFile(join(OUT, 'report.json'))` are the same API
 * and different risks. So the inventory has two layers:
 *
 *   1. a curated table of every writer that can reach a TRACKED path, with its
 *      trigger, category and safe override;
 *   2. a scan that proves the curated table is complete — every write call site
 *      in `tests/`, `eval/` and `scripts/` is either covered by a curated entry
 *      or classified as temporary output by the shape of its target.
 *
 * A site the scan cannot classify is reported, not dropped. The brief is
 * explicit that the scan is candidate discovery, not a verdict.
 *
 * ## Categories
 *
 *   temporary-test-output        a mkdtemp/makeTemp directory
 *   run-scoped-evidence          a run record outside the repository
 *   latest-convenience-copy      a `latest` copy of run-scoped evidence
 *   frozen-historical-artifact   evidence that must never be rewritten
 *   tracked-generated-config     generated configuration committed on purpose
 *   tracked-generated-source     source generated from the vendor tree
 *   build-artifact               gitignored build output
 *   unknown                      needs a human decision
 *
 * @module eval/c1/side-effects
 */

