/** A target expression that names the repository rather than a temp directory. */
const REPO_TARGET = /(process\.cwd\(\)|import\.meta\.dirname|\bROOT\b|\bOUT\b|\boutDir\b|'docs'|"docs"|'scripts'|"scripts"|cordis\.patch|tsconfig\.json|vendor-paths|vendor-types-paths|MANIFEST\.json)/u

function walk(dir, prefix = '') {
  const full = join(ROOT, dir)
  if (!existsSync(full)) return []
  const found = []
  for (const entry of readdirSync(full, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'vendor' || entry.name === 'dist') continue
    const rel = prefix === '' ? join(dir, entry.name) : join(prefix, entry.name)
    if (entry.isDirectory()) found.push(...walk(rel, rel))
    else if (/\.(ts|mjs|cjs|js)$/u.test(entry.name)) found.push(rel)
  }
  return found
}

function firstArgument(line, start) {
  // The scan is line-oriented on purpose: every write site in this repository
  // names its target on the same line, and a parser would be a second
  // implementation of JavaScript for a report.
  const open = line.indexOf('(', start)
  if (open === -1) return ''
  let depth = 0
  for (let index = open; index < line.length; index += 1) {
    const ch = line[index]
    if (ch === '(') depth += 1
    else if (ch === ')') {
      depth -= 1
      if (depth === 0) return line.slice(open + 1, index).split(',')[0]?.trim() ?? ''
    }
  }
  return line.slice(open + 1).trim()
}

/** Whether a curated entry covers a file (exact, or a `dir/*` pattern). */
function curatedFor(file, writer) {
  if (!writer.file.includes('*')) return file === writer.file
  return file.startsWith(writer.file.split('*')[0])
}

function scan() {
  const sites = []
  for (const dir of SCAN_ROOTS) {
    for (const file of walk(dir)) {
      const source = readFileSync(join(ROOT, file), 'utf8')
      const lines = source.split('\n')
      for (let index = 0; index < lines.length; index += 1) {
        const line = lines[index]
        if (line.trimStart().startsWith('*') || line.trimStart().startsWith('//')) continue
        WRITE_API.lastIndex = 0
        let match
        while ((match = WRITE_API.exec(line)) !== null) {
          const api = match[1]
          // `mkdir` alone is not a write of content; it is kept only when the
          // same line also names a report path.
          if ((api === 'mkdir' || api === 'mkdirSync') && !/report|out|write/u.test(line)) continue
          const target = firstArgument(line, match.index)
          const normalized = file.replace(/\\/gu, '/')
          const curated = WRITERS.find(writer => curatedFor(normalized, writer))
          const looksRepo = REPO_TARGET.test(target)
          sites.push({
            file: normalized,
            line: index + 1,
            api,
            target,
            curated: curated?.id ?? null,
            classification: curated !== undefined
              ? curated.category
              : (looksRepo ? 'unknown' : 'temporary-test-output'),
          })
        }
      }
    }
  }
  return sites
}

function main() {
  const sites = scan()
  const byApi = {}
  const byClassification = {}
  for (const site of sites) {
    byApi[site.api] = (byApi[site.api] ?? 0) + 1
    byClassification[site.classification] = (byClassification[site.classification] ?? 0) + 1
  }

  // A curated file may legitimately have more sites than the table lists (a
  // test with several temp writes). What must not happen is a repo-shaped write
  // in a file the table does not cover.
  const uncoveredRepoFiles = [...new Set(
    sites
      .filter(site => site.classification === 'unknown')
      .map(site => site.file),
  )].sort()

  const observations = existsSync(OUT)
    ? readdirSync(OUT)
      .filter(name => /^observation-.*\.json$/u.test(name))
      .sort()
      .map(name => {
        const observation = JSON.parse(readFileSync(join(OUT, name), 'utf8'))
        return {
          id: observation.id,
          command: observation.command,
          exitCode: observation.exitCode,
          drifted: observation.drifted,
          drift: observation.drift.map(row => row.path),
        }
      })
    : []

  const report = {
    schemaVersion: 1,
    work: 'EF-C1',
    generator: 'eval/c1/side-effects.mjs',
    sourceCommit: readGitHead(),
    generatedAt: new Date().toISOString(),
    rule: 'a tracked path may only be written by an explicit generate/promote operation',
    scan: {
      roots: SCAN_ROOTS,
      files: [...new Set(sites.map(site => site.file))].length,
      sites: sites.length,
      byApi,
      byClassification,
      uncoveredRepoFiles,
    },
    writers: WRITERS,
    observations,
    sites,
  }

  mkdirSync(OUT, { recursive: true })
  writeFileSync(join(OUT, 'side-effect-inventory.json'), `${JSON.stringify(report, null, 2)}\n`, 'utf8')
  process.stdout.write(
    `side effects: ${sites.length} write site(s) in ${report.scan.files} file(s); `
    + `${uncoveredRepoFiles.length} uncovered repo-shaped file(s)\n`,
  )
  for (const file of uncoveredRepoFiles) process.stdout.write(`  uncovered: ${file}\n`)
  process.stdout.write(`wrote ${join(OUT, 'side-effect-inventory.json')}\n`)
}

function readGitHead() {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim()
  } catch {
    return 'unknown'
  }
}

main()
